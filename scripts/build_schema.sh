#!/usr/bin/env bash
# Generate database/schema.sql from database/schema.dbml, then append database/extras.sql.
# Usage: scripts/build_schema.sh   (needs Node; fetches @dbml/cli on first run)
set -euo pipefail
cd "$(dirname "$0")/../database"

{
  echo "-- GENERATED by scripts/build_schema.sh from schema.dbml + extras.sql. Do not edit by hand."
  echo
  npx -y -p @dbml/cli@11.0.0 dbml2sql schema.dbml --postgres
  echo
  cat extras.sql
} > schema.sql
rm -f dbml-error.log
echo "wrote database/schema.sql"
